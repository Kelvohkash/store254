function hexToRgb(hex) {
  const clean = String(hex || "#000000").replace("#", "");
  const full = clean.length === 3 ? [...clean].map((c) => c + c).join("") : clean;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
}

function rgbToHex([r, g, b]) {
  return `#${[r, g, b].map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0")).join("")}`;
}

function mixHex(hexA, hexB, weightA = 0.5) {
  const a = hexToRgb(hexA);
  const b = hexToRgb(hexB);
  return rgbToHex([
    a[0] * weightA + b[0] * (1 - weightA),
    a[1] * weightA + b[1] * (1 - weightA),
    a[2] * weightA + b[2] * (1 - weightA),
  ]);
}

function buildFixedColorTokens(defaultColors = {}, customColors = {}) {
  const primary = customColors.primary || defaultColors.fg || "#15803d";
  const paper = customColors.paper || defaultColors.bg || "#edf5ee";
  const [pr, pg, pb] = hexToRgb(primary);
  return {
    primary,
    primaryHover: customColors.primaryHover || defaultColors.primaryHover || mixHex(primary, "#000000", 0.82),
    primarySubtle: customColors.primarySubtle || defaultColors.primarySubtle || mixHex("#ffffff", primary, 0.88),
    primaryGlow: customColors.primaryGlow || defaultColors.primaryGlow || `rgba(${pr}, ${pg}, ${pb}, 0.26)`,
    onPrimary: customColors.onPrimary || defaultColors.onPrimary || "#ffffff",
    paper,
    white: customColors.white || defaultColors.white || "#ffffff",
    surfaceSubtle: customColors.surfaceSubtle || defaultColors.surfaceSubtle || mixHex(paper, "#ffffff", 0.45),
    ink: customColors.ink || defaultColors.ink || mixHex("#0f172a", primary, 0.92),
    muted: customColors.muted || defaultColors.muted || mixHex("#475569", primary, 0.9),
    line: customColors.line || defaultColors.line || mixHex(paper, "#0f172a", 0.84),
    mediaBg: customColors.mediaBg || defaultColors.mediaBg || mixHex(paper, "#ffffff", 0.55),
  };
}

